/// Double-quoted for `ExecStart=` and `Environment=`: `\` and `"` escaped,
/// `%` doubled so systemd does not read it as a specifier.
fn quoted(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '%' => out.push_str("%%"),
            '\n' => out.push_str("\\n"),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

/// How a unit starts syncfast.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Launcher {
    /// The binary, the rclone it must use and the restic the backups run,
    /// by absolute path. No restic when none was found.
    Native {
        bin: String,
        rclone: String,
        restic: Option<String>,
    },
    /// `flatpak run` of the app: the sandbox brings its own rclone, found on
    /// its `PATH` (ADR 0006).
    Flatpak { app_id: String },
}

impl Launcher {
    /// The value of `ExecStart=` for `syncfast <args>`.
    fn exec(&self, args: &str) -> String {
        match self {
            Self::Native { bin, .. } => format!("{} {args}", quoted(bin)),
            Self::Flatpak { app_id } => {
                format!("flatpak run --die-with-parent --command=syncfast {app_id} {args}")
            }
        }
    }

    /// The `Environment=` line, with its newline, or nothing.
    fn environment_line(&self) -> String {
        match self {
            Self::Native { rclone, .. } => {
                format!(
                    "Environment={}\n",
                    quoted(&format!("SYNCFAST_RCLONE={rclone}"))
                )
            }
            Self::Flatpak { .. } => String::new(),
        }
    }

    /// The `Environment=` lines of a backup unit: rclone, then restic when
    /// one was found.
    fn backup_environment_lines(&self) -> String {
        let mut lines = self.environment_line();
        if let Self::Native {
            restic: Some(restic),
            ..
        } = self
        {
            lines.push_str("Environment=");
            lines.push_str(&quoted(&format!("SYNCFAST_RESTIC={restic}")));
            lines.push('\n');
        }
        lines
    }
}

/// `syncfast-<id>.service`: one oneshot round, started by the timer, the
/// watcher or `Sync Now`.
#[must_use]
pub fn pair_service(pair: &Pair, launcher: &Launcher) -> String {
    format!(
        "{UNIT_HEADER}\n\
         [Unit]\n\
         Description=syncfast: {name}\n\
         \n\
         [Service]\n\
         Type=oneshot\n\
         ExecStart={exec}\n\
         {env}\
         KillSignal=SIGINT\n\
         TimeoutStartSec=infinity\n\
         TimeoutStopSec=180\n\
         Nice=10\n\
         IOSchedulingClass=idle\n",
        name = pair.name.replace('%', "%%"),
        exec = launcher.exec(&format!("run {}", pair.id)),
        env = launcher.environment_line(),
    )
}

/// `syncfast-<id>.timer`: the next round starts `interval` after the
/// previous one ended.
#[must_use]
pub fn pair_timer(pair: &Pair, behavior: &Behavior) -> String {
    format!(
        "{UNIT_HEADER}\n\
         [Unit]\n\
         Description=syncfast timer: {name}\n\
         \n\
         [Timer]\n\
         OnStartupSec=2min\n\
         OnUnitInactiveSec={interval}s\n\
         Unit={service}\n\
         \n\
         [Install]\n\
         WantedBy=timers.target\n",
        name = pair.name.replace('%', "%%"),
        interval = behavior.interval.as_secs(),
        service = service_name(&pair.id),
    )
}

/// `syncfast-backup_<id>.service`: one backup, started by the timer, a
