/// The syncfast binary the units call: the running executable with
/// symlinks resolved.
///
/// # Errors
/// The executable's path cannot be read or resolved.
pub fn current_binary() -> io::Result<PathBuf> {
    std::env::current_exe()?.canonicalize()
}

/// What `apply` needs from the outside world.
pub struct ApplyEnv<'a> {
    pub paths: &'a Paths,
    pub rclone: &'a Rclone,
    /// Absolute path of the syncfast binary, see [`current_binary`].
    pub bin: &'a Path,
    pub mode: SystemdMode,
    pub systemctl: &'a dyn Systemctl,
    /// The Flatpak app id when running in the sandbox: the units then call
    /// `flatpak run` instead of `bin` (ADR 0006).
    pub flatpak_id: Option<&'a str>,
    /// How long a removal waits for a running round.
    pub pair_lock_timeout: Duration,
    /// The restic the backup units run with, see [`restic::locate_binary`].
    pub restic: Option<PathBuf>,
}

impl<'a> ApplyEnv<'a> {
    #[must_use]
    pub fn new(
        paths: &'a Paths,
        rclone: &'a Rclone,
        bin: &'a Path,
        mode: SystemdMode,
        systemctl: &'a dyn Systemctl,
    ) -> Self {
        Self {
            paths,
            rclone,
            bin,
            mode,
            systemctl,
            flatpak_id: None,
            pair_lock_timeout: PAIR_LOCK_TIMEOUT,
            restic: restic::locate_binary(),
        }
    }

    #[must_use]
    pub fn with_flatpak_id(mut self, flatpak_id: Option<&'a str>) -> Self {
        self.flatpak_id = flatpak_id;
        self
    }

    /// Overrides the restic the backup units point at; `None` leaves the
    /// `SYNCFAST_RESTIC` line out.
    #[must_use]
    pub fn with_restic(mut self, restic: Option<PathBuf>) -> Self {
        self.restic = restic;
        self
    }
}

impl fmt::Debug for ApplyEnv<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("ApplyEnv")
            .field("paths", &self.paths)
            .field("rclone", &self.rclone)
            .field("bin", &self.bin)
            .field("mode", &self.mode)
            .finish_non_exhaustive()
    }
}

/// One step of `apply` that did not work; the rest of `apply` still ran.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ApplyFailure {
    pub pair_id: Option<String>,
    pub command: String,
    pub detail: String,
}

/// What `apply` found. Empty when everything went through.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ApplyReport {
    /// The config has a global problem; nothing was changed.
    pub config_error: Option<String>,
    /// Syncs that got no units because their config is invalid.
    pub invalid_pairs: Vec<PairError>,
    /// Backups that got no units because their config is invalid.
    pub invalid_backups: Vec<BackupError>,
    pub failures: Vec<ApplyFailure>,
}

impl ApplyReport {
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.config_error.is_none()
            && self.invalid_pairs.is_empty()
            && self.invalid_backups.is_empty()
            && self.failures.is_empty()
    }

    /// 2 for a config the user must fix, 1 when a step failed, else 0.
    #[must_use]
    pub fn exit_code(&self) -> u8 {
        if self.config_error.is_some() {
            2
        } else {
            u8::from(!self.failures.is_empty())
        }
    }
}

impl fmt::Display for ApplyReport {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if let Some(error) = &self.config_error {
            writeln!(f, "{error}")?;
        }
        for invalid in &self.invalid_pairs {
            writeln!(f, "{}: not applied: {}", invalid.pair_id, invalid.message)?;
        }
        for invalid in &self.invalid_backups {
            writeln!(
                f,
                "backup {}: not applied: {}",
                invalid.backup_id, invalid.message
            )?;
        }
        for failure in &self.failures {
            match &failure.pair_id {
                Some(id) => writeln!(f, "{id}: {}: {}", failure.command, failure.detail)?,
                None => writeln!(f, "{}: {}", failure.command, failure.detail)?,
            }
        }
        Ok(())
    }
}

/// How much of a sync `apply` takes away.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Removal {
    /// Units only: the sync is still in the config but invalid.
    Units,
    /// The sync left the config: units, state, filters and bisync listings,
    /// and the versions folder when asked.
    Sync { delete_versions: bool },
}

/// How much of a backup `apply` takes away.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum BackupRemoval {
    /// Units only: the backup is still in the config but invalid.
    Units,
    /// The backup left the config: units, state folder and lock file. The
    /// repository and the key stay.
    Backup,
}

struct Applier<'a, 'e> {
    env: &'a ApplyEnv<'e>,
    dir: PathBuf,
    report: ApplyReport,
    /// Whether a unit file was written or deleted, so systemd must reload.
    units_changed: bool,
}

/// Reconciles the units with the config: removes what left it, writes what
/// changed, and enables or disables the timers. `delete_versions` lists
/// removed syncs whose versions folder goes too.
pub async fn apply(env: &ApplyEnv<'_>, delete_versions: &[String]) -> ApplyReport {
    let mut applier = Applier {
        env,
        dir: env.mode.units_dir(env.paths),
        report: ApplyReport::default(),
        units_changed: false,
    };
    if let Err(err) = Config::migrate(env.paths).await {
        applier.fail(None, "migrate config.toml", err.to_string());
    }
    let _apply_lock = match lock_apply(env.paths).await {
        Ok(lock) => lock,
        Err(err) => {
            applier.fail(None, "lock apply", err.to_string());
            return applier.report;
        }
    };
    applier.reconcile(delete_versions).await;
    applier.report
}

async fn lock_apply(paths: &Paths) -> io::Result<File> {
    let (dir, path) = (paths.runtime_subdir(), paths.apply_lock_file());
    tokio::task::spawn_blocking(move || {
        std::fs::create_dir_all(dir)?;
        let file = std::fs::OpenOptions::new()
            .create(true)
            .write(true)
            .truncate(false)
            .open(path)?;
        file.lock()?;
        Ok(file)
    })
    .await
    .unwrap_or_else(|join| Err(io::Error::other(join)))
}

impl Applier<'_, '_> {
    fn fail(&mut self, pair_id: Option<&str>, command: impl Into<String>, detail: String) {
        self.report.failures.push(ApplyFailure {
            pair_id: pair_id.map(str::to_owned),
            command: command.into(),
            detail,
        });
    }

    async fn systemctl(&mut self, pair_id: Option<&str>, args: &[&str]) {
        if self.env.mode == SystemdMode::Off {
            return;
        }
        if let Err(stderr) = self.env.systemctl.run(args).await {
            self.fail(pair_id, command_text(args), stderr);
        }
    }

    /// Reloads systemd when a unit changed or an earlier reload failed, and
    /// remembers a failure in `reload-pending`.
    async fn reload_if_needed(&mut self) {
        let marker = self.env.paths.reload_pending_file();
        if !self.units_changed && !path_exists(&marker).await {
            return;
        }
        let failures = self.report.failures.len();
        self.systemctl(None, &["daemon-reload"]).await;
        if self.report.failures.len() > failures {
            if let Err(err) = write_marker(&marker).await {
                log::warn!("cannot record the pending reload: {err}");
            }
        } else if let Err(err) = tokio::fs::remove_file(&marker).await
            && err.kind() != io::ErrorKind::NotFound
        {
            log::warn!("cannot clear the pending reload: {err}");
        }
    }

    async fn reconcile(&mut self, delete_versions: &[String]) {
        let env = self.env;
        let config = match Config::load(env.paths).await {
            Ok(config) => config,
            Err(err) => {
                self.report.config_error = Some(err.to_string());
                return;
            }
        };
        let accounts = match env.rclone.listremotes().await {
            Ok(accounts) => accounts,
            // Without the account list every sync would look invalid and
            // lose its units.
            Err(err) => {
                self.fail(None, "rclone listremotes", err.to_string());
                return;
            }
        };
        let launcher = match resolve_launcher(env).await {
            Ok(launcher) => launcher,
            Err(err) => {
                self.fail(None, "resolve the launcher", err);
                return;
            }
        };
        let validation = config.validate(env.paths, &accounts);
        let configured: HashSet<&str> = config.pairs().iter().map(|p| p.id.as_str()).collect();
        let invalid: HashSet<&str> = validation
            .errors
            .iter()
            .map(|error| error.pair_id.as_str())
            .collect();

        let installed = installed_ids(&self.dir).await;
        let mut removed: BTreeSet<&str> = installed
            .iter()
            .map(String::as_str)
            .filter(|id| !configured.contains(id))
            .collect();
        let mut requested = HashSet::new();
        for id in delete_versions {
            if !valid_id(id) {
                self.fail(
                    Some(id),
                    "delete versions",
                    "not a valid sync id".to_owned(),
                );
            } else if id == RESERVED_ID {
                self.fail(
                    Some(id),
                    "delete versions",
                    format!("\"{RESERVED_ID}\" is reserved for the watcher"),
                );
            } else if configured.contains(id.as_str()) {
                self.fail(
                    Some(id),
                    "delete versions",
                    "the sync still exists; remove it first".to_owned(),
                );
            } else {
                requested.insert(id.as_str());
                removed.insert(id.as_str());
            }
        }
        for id in removed {
            let delete_versions = requested.contains(id);
            self.remove(id, Removal::Sync { delete_versions }).await;
        }
        for id in installed
            .iter()
            .map(String::as_str)
            .filter(|id| invalid.contains(id))
        {
            self.remove(id, Removal::Units).await;
        }

        for error in &validation.errors {
            self.report.invalid_pairs.push(error.clone());
            if let Some(pair) = config.pairs().iter().find(|p| p.id == error.pair_id) {
                self.mark_config_error(pair, &error.message).await;
            }
        }

        self.write_units(&validation.pairs, &config.defaults(), &launcher)
            .await;
        let backups = config.validate_backups(env.paths, &accounts);
        self.reconcile_backups(&config, &backups, &launcher).await;
        self.reload_if_needed().await;
        for pair in &validation.pairs {
            let timer = timer_name(&pair.id);
            let verb = if pair.enabled { "enable" } else { "disable" };
            self.systemctl(Some(&pair.id), &[verb, "--now", &timer])
                .await;
        }
        for backup in &backups.backups {
            let timer = backup_timer_name(&backup.id);
            let verb = if backup.enabled { "enable" } else { "disable" };
            self.systemctl(Some(&backup.id), &[verb, "--now", &timer])
                .await;
        }
        let watcher = watch_service_name();
        self.systemctl(None, &["enable", &watcher]).await;
        self.systemctl(None, &["restart", &watcher]).await;
    }

    /// Removes one sync's units (and the rest of it for [`Removal::Sync`]),
    /// after stopping the timer and waiting for a running round.
    async fn remove(&mut self, id: &str, removal: Removal) {
        let (service, timer) = (service_name(id), timer_name(id));
        self.stop_units(id, &service, &timer).await;
        let lock = match lock_pair(self.env.paths, id, self.env.pair_lock_timeout).await {
            Ok(Some(lock)) => lock,
            Ok(None) => {
                let seconds = self.env.pair_lock_timeout.as_secs();
                self.fail(
                    Some(id),
                    "wait for the running sync",
                    format!("still running after {seconds} s; removal left for the next apply"),
                );
                return;
            }
            Err(err) => {
                self.fail(Some(id), "lock the sync", err.to_string());
                return;
            }
        };
        self.delete_units(id, &service, &timer).await;
        if let Removal::Sync { delete_versions } = removal {
            let paths = self.env.paths;
            let mut doomed = vec![
                (paths.pair_state_dir(id), true),
                (paths.filters_file(id), false),
                (md5_beside(&paths.filters_file(id)), false),
                (paths.bisync_workdir(id), true),
            ];
            if delete_versions {
                doomed.push((paths.versions_dir(id), true));
            }
            for (path, is_dir) in doomed {
                self.delete(id, &path, is_dir).await;
            }
            self.delete(id, &paths.lock_file(id), false).await;
        }
        drop(lock);
    }

    /// Deletes a file or folder; true when something was there.
    async fn delete(&mut self, id: &str, path: &Path, is_dir: bool) -> bool {
        let outcome = if is_dir {
            tokio::fs::remove_dir_all(path).await
        } else {
            tokio::fs::remove_file(path).await
        };
        match outcome {
            Ok(()) => true,
            Err(err) if err.kind() == io::ErrorKind::NotFound => false,
            Err(err) => {
                self.fail(
                    Some(id),
                    format!("delete {}", path.display()),
                    err.to_string(),
                );
                false
            }
        }
    }

    async fn mark_config_error(&mut self, pair: &Pair, message: &str) {
        let paths = self.env.paths;
        let mut state = match State::load(paths, &pair.id).await {
            Ok(state) => state,
            Err(err) => {
                self.fail(Some(&pair.id), "read the sync's state", err.to_string());
                return;
            }
        };
        let unchanged = state
            .gate
            .as_ref()
            .is_some_and(|gate| gate.kind == GateKind::ConfigError && gate.detail == message);
        if unchanged {
            return;
        }
        set_gate(
            &mut state,
            GateKind::ConfigError,
            message.to_owned(),
            None,
            Timestamp::now(),
        );
        if let Err(err) = state.save(paths, &pair.id).await {
            self.fail(Some(&pair.id), "write the sync's state", err.to_string());
        }
    }

    async fn write_units(&mut self, pairs: &[Pair], defaults: &Behavior, launcher: &Launcher) {
        let mut units = vec![(watch_service_name(), watch_service(launcher))];
        for pair in pairs {
            units.push((service_name(&pair.id), pair_service(pair, launcher)));
            let behavior = Behavior::for_pair(defaults, pair);
            units.push((timer_name(&pair.id), pair_timer(pair, &behavior)));
        }
        for (name, contents) in units {
            let path = self.dir.join(&name);
            match write_if_changed(path, contents).await {
                Ok(true) => self.units_changed = true,
                Ok(false) => {}
                Err(err) => self.fail(None, format!("write {name}"), err.to_string()),
            }
        }
    }

    async fn stop_units(&mut self, id: &str, service: &str, timer: &str) {
        if path_exists(&self.dir.join(timer)).await {
            self.systemctl(Some(id), &["disable", "--now", timer]).await;
        }
        if path_exists(&self.dir.join(service)).await {
            self.systemctl(Some(id), &["stop", service]).await;
        }
    }

    async fn delete_units(&mut self, id: &str, service: &str, timer: &str) {
        for name in [service, timer] {
            let path = self.dir.join(name);
            if self.delete(id, &path, false).await {
                self.units_changed = true;
            }
        }
    }

    /// Backups that left the config lose their units and state; invalid
    /// ones lose the units and get the `config_error` gate; valid ones get
    /// their units written. The timers are enabled after the reload.
    async fn reconcile_backups(
        &mut self,
        config: &Config,
        validation: &BackupValidation,
        launcher: &Launcher,
    ) {
        let configured: HashSet<&str> = config.backups().iter().map(|b| b.id.as_str()).collect();
        let invalid: HashSet<&str> = validation
            .errors
            .iter()
            .map(|error| error.backup_id.as_str())
            .collect();
        let installed = installed_backup_ids(&self.dir).await;
        for id in installed
            .iter()
            .filter(|id| !configured.contains(id.as_str()))
        {
            self.remove_backup(id, BackupRemoval::Backup).await;
        }
        for id in installed.iter().filter(|id| invalid.contains(id.as_str())) {
            self.remove_backup(id, BackupRemoval::Units).await;
        }
        for error in &validation.errors {
            self.report.invalid_backups.push(error.clone());
            self.mark_backup_config_error(&error.backup_id, &error.message)
                .await;
        }
        self.write_backup_units(&validation.backups, launcher).await;
        for backup in &validation.backups {
            self.clear_backup_config_error(&backup.id).await;
        }
    }

    /// Removes one backup's units (and its state folder for
    /// [`BackupRemoval::Backup`]), after stopping the timer and waiting for
    /// a running backup. The repository and the key are never touched.
    async fn remove_backup(&mut self, id: &str, removal: BackupRemoval) {
        let (service, timer) = (backup_service_name(id), backup_timer_name(id));
        self.stop_units(id, &service, &timer).await;
        let paths = self.env.paths;
        let lock = match lock_within(
            paths,
            paths.backup_lock_file(id),
            self.env.pair_lock_timeout,
        )
        .await
        {
            Ok(Some(lock)) => lock,
            Ok(None) => {
                let seconds = self.env.pair_lock_timeout.as_secs();
                self.fail(
                    Some(id),
                    "wait for the running backup",
                    format!("still running after {seconds} s; removal left for the next apply"),
                );
                return;
            }
            Err(err) => {
                self.fail(Some(id), "lock the backup", err.to_string());
                return;
            }
        };
        self.delete_units(id, &service, &timer).await;
        if removal == BackupRemoval::Backup {
            self.delete(id, &paths.backup_state_dir(id), true).await;
            self.delete(id, &paths.backup_lock_file(id), false).await;
        }
        drop(lock);
    }

    async fn mark_backup_config_error(&mut self, id: &str, message: &str) {
        // An id that is not valid has no state folder to write to.
        if !valid_id(id) {
            return;
        }
        let paths = self.env.paths;
        let mut state = match BackupState::load(paths, id).await {
            Ok(state) => state,
            Err(err) => {
                self.fail(Some(id), "read the backup's state", err.to_string());
                return;
            }
        };
        let current = state
            .gate
            .as_ref()
            .filter(|gate| gate.kind == GateKind::ConfigError);
        if current.is_some_and(|gate| gate.detail == message) {
            return;
        }
        let since = current.map_or_else(Timestamp::now, |gate| gate.since);
        state.gate = Some(Gate {
            kind: GateKind::ConfigError,
            since,
            detail: message.to_owned(),
            fault: None,
            auto_checked: None,
        });
        if let Err(err) = state.save(paths, id).await {
            self.fail(Some(id), "write the backup's state", err.to_string());
        }
    }

    /// A `config_error` gate ends once the backup is valid again; the next
    /// one must notify again. A state that cannot be read is left to the
    /// next run.
    async fn clear_backup_config_error(&mut self, id: &str) {
        let paths = self.env.paths;
        let mut state = match BackupState::load(paths, id).await {
            Ok(state) => state,
            Err(err) => {
                log::warn!("cannot read the state of backup {id}: {err}");
                return;
            }
        };
        if state
            .gate
            .as_ref()
            .is_none_or(|gate| gate.kind != GateKind::ConfigError)
        {
            return;
        }
        state.gate = None;
        state
            .notified
            .retain(|key| *key != GateKind::ConfigError.notified_key());
        if let Err(err) = state.save(paths, id).await {
            self.fail(Some(id), "write the backup's state", err.to_string());
        }
    }

    async fn write_backup_units(&mut self, backups: &[BackupConfig], launcher: &Launcher) {
        for backup in backups {
            let units = [
                (
                    backup_service_name(&backup.id),
                    backup_service(backup, launcher),
                ),
                (backup_timer_name(&backup.id), backup_timer(backup)),
            ];
            for (name, contents) in units {
                match write_if_changed(self.dir.join(&name), contents).await {
                    Ok(true) => self.units_changed = true,
                    Ok(false) => {}
                    Err(err) => {
                        self.fail(Some(&backup.id), format!("write {name}"), err.to_string());
                    }
                }
            }
        }
    }
}

fn md5_beside(filters: &Path) -> PathBuf {
    let mut name = filters.as_os_str().to_owned();
    name.push(".md5");
    PathBuf::from(name)
}

async fn write_marker(path: &Path) -> io::Result<()> {
    if let Some(dir) = path.parent() {
        tokio::fs::create_dir_all(dir).await?;
    }
    tokio::fs::write(path, b"").await
}

async fn path_exists(path: &Path) -> bool {
    tokio::fs::try_exists(path).await.unwrap_or(false)
}

/// How the units must start syncfast: the binary, rclone and restic by
/// absolute path, or `flatpak run` inside the sandbox. A missing restic is
/// not an error here: `backup-run` reports it.
async fn resolve_launcher(env: &ApplyEnv<'_>) -> Result<Launcher, String> {
    if let Some(app_id) = env.flatpak_id {
        return Ok(Launcher::Flatpak {
            app_id: app_id.to_owned(),
        });
    }
    let rclone = tokio::fs::canonicalize(env.rclone.bin())
        .await
        .map_err(|err| format!("{}: {err}", env.rclone.bin().display()))?;
    let as_text = |path: &Path| {
        path.to_str()
            .map(str::to_owned)
            .ok_or_else(|| format!("{} is not valid UTF-8", path.display()))
    };
    let restic = match &env.restic {
        Some(restic) => tokio::fs::canonicalize(restic)
            .await
            .ok()
            .and_then(|path| path.to_str().map(str::to_owned)),
        None => None,
    };
    Ok(Launcher::Native {
        bin: as_text(env.bin)?,
        rclone: as_text(&rclone)?,
        restic,
    })
}

/// Writes `contents` unless the file already holds exactly that. True when
/// the file changed.
async fn write_if_changed(path: PathBuf, contents: String) -> io::Result<bool> {
    match tokio::fs::read(&path).await {
        Ok(existing) if existing == contents.as_bytes() => return Ok(false),
        Ok(_) => {}
        Err(err) if err.kind() == io::ErrorKind::NotFound => {}
        Err(err) => return Err(err),
    }
    tokio::task::spawn_blocking(move || fastframe_file::write(&path, contents))
        .await
        .unwrap_or_else(|join| Err(io::Error::other(join)))?;
    Ok(true)
}

/// Ids of the syncs that have generated units in `dir`. Files that do not
/// start with [`UNIT_HEADER`] are the user's and are ignored.
async fn installed_ids(dir: &Path) -> BTreeSet<String> {
    installed(dir, UNIT_PREFIX, |id| id != RESERVED_ID && valid_id(id)).await
}

/// Ids of the backups that have generated units in `dir`.
async fn installed_backup_ids(dir: &Path) -> BTreeSet<String> {
    installed(dir, BACKUP_PREFIX, valid_id).await
}

/// The ids `accepts` takes out of the `<prefix><id>.service|.timer` files
/// of `dir` that start with [`UNIT_HEADER`].
async fn installed(dir: &Path, prefix: &str, accepts: fn(&str) -> bool) -> BTreeSet<String> {
    let mut ids = BTreeSet::new();
    let Ok(mut entries) = tokio::fs::read_dir(dir).await else {
        return ids;
    };
    while let Ok(Some(entry)) = entries.next_entry().await {
        let name = entry.file_name();
        let Some(id) = name
            .to_str()
            .and_then(|name| name.strip_prefix(prefix))
            .and_then(|rest| {
                rest.strip_suffix(SERVICE_SUFFIX)
                    .or_else(|| rest.strip_suffix(TIMER_SUFFIX))
            })
        else {
            continue;
        };
        if !accepts(id) {
            continue;
        }
        let generated = tokio::fs::read_to_string(entry.path())
            .await
            .is_ok_and(|text| text.starts_with(UNIT_HEADER));
        if generated {
            ids.insert(id.to_owned());
        }
    }
    ids
}

