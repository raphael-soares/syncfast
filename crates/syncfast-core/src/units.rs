/// First line of every generated unit; also how `apply` recognizes the
/// units it owns.
pub const UNIT_HEADER: &str = "# Generated by syncfast. Do not edit; run \"syncfast apply\".";
/// How long a removal waits for a running round before leaving the sync
/// for the next `apply`.
pub const PAIR_LOCK_TIMEOUT: Duration = Duration::from_secs(300);
const UNIT_PREFIX: &str = "syncfast-";
const BACKUP_PREFIX: &str = "syncfast-backup_";

const SERVICE_SUFFIX: &str = ".service";
const TIMER_SUFFIX: &str = ".timer";
const SYSTEMD_OFF_VALUE: &str = "off";
const SYSTEMD_VAR: &str = "SYNCFAST_SYSTEMD";

/// Whether `apply` and the watcher talk to the user's systemd.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SystemdMode {
    User,
    /// Units go to a preview folder and nothing is started: dev mode and
    /// tests.
    Off,
}

impl SystemdMode {
    /// `Off` when `SYNCFAST_SYSTEMD=off`.
    #[must_use]
    pub fn from_env() -> Self {
        Self::from_value(std::env::var_os(SYSTEMD_VAR).as_deref())
    }

    fn from_value(value: Option<&OsStr>) -> Self {
        if value == Some(OsStr::new(SYSTEMD_OFF_VALUE)) {
            Self::Off
        } else {
            Self::User
        }
    }

    /// Folder the units are written to.
    #[must_use]
    pub fn units_dir(self, paths: &Paths) -> PathBuf {
        match self {
            Self::User => paths.systemd_user_dir(),
            Self::Off => paths.units_preview_dir(),
        }
    }
}

/// Runs `systemctl --user <args>`; the fake in tests records the calls.
pub trait Systemctl: Send + Sync {
    /// `Err` carries the command's last line of stderr.
    fn run<'a>(&'a self, args: &'a [&'a str]) -> BoxFuture<'a, Result<(), String>>;
}

/// `systemctl --user`, on the host's systemd when running in the Flatpak
/// sandbox (ADR 0006).
#[derive(Debug, Clone, Copy, Default)]
pub struct UserSystemctl {
    on_host: bool,
}

impl UserSystemctl {
    /// Goes through `flatpak-spawn --host` exactly when `FLATPAK_ID` is set.
    #[must_use]
    pub fn detect() -> Self {
        Self {
            on_host: flatpak::app_id().is_some(),
        }
    }
}

impl Systemctl for UserSystemctl {
    fn run<'a>(&'a self, args: &'a [&'a str]) -> BoxFuture<'a, Result<(), String>> {
        Box::pin(async move {
            let (program, full_args) = flatpak::systemctl_command(self.on_host, args);
            let output = Command::new(program)
                .args(full_args)
                .stdin(Stdio::null())
                .stdout(Stdio::null())
                .stderr(Stdio::piped())
                .kill_on_drop(true)
                .output()
                .await
                .map_err(|err| format!("cannot run {program}: {err}"))?;
            if output.status.success() {
                return Ok(());
            }
            let stderr = String::from_utf8_lossy(&output.stderr);
            Err(stderr
                .lines()
                .rev()
                .map(str::trim)
                .find(|line| !line.is_empty())
                .map_or_else(|| format!("exited with {}", output.status), str::to_owned))
        })
    }
}

/// `systemctl --user <args>` as shown in reports and logs.
#[must_use]
pub fn command_text(args: &[&str]) -> String {
    format!("systemctl --user {}", args.join(" "))
}

