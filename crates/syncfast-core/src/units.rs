/// `syncfast-backup_<id>.timer`: a calendar schedule that catches up a run
/// missed while the machine was off.
#[must_use]
pub fn backup_timer(backup: &BackupConfig) -> String {
    let calendar = match Every::parse(&backup.every).unwrap_or(Every::Daily) {
        Every::Hourly => "hourly",
        Every::Daily => "*-*-* 03:00:00",
        Every::Weekly => "Mon *-*-* 03:00:00",
    };
    format!(
        "{UNIT_HEADER}\n\
         [Unit]\n\
         Description=syncfast backup timer: {name}\n\
         \n\
         [Timer]\n\
         OnCalendar={calendar}\n\
         Persistent=true\n\
         RandomizedDelaySec=10min\n\
         Unit={service}\n\
         \n\
         [Install]\n\
         WantedBy=timers.target\n",
        name = backup.name.replace('%', "%%"),
        service = backup_service_name(&backup.id),
    )
}

