pub const GENERATED_HEADER: &str = "# Generated by syncfast. Do not edit.";

/// Preset with no static rules: [`render`] adds one anchored rule per
/// repository [`find_git_repos`] finds.
pub const GIT_REPOS: &str = "git_repos";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Preset {
    pub name: &'static str,
    pub rules: &'static [&'static str],
}

/// In render order.
pub const PRESETS: [Preset; 3] = [
    Preset {
        name: "system_junk",
        rules: &[
            "- .directory",
            "- .Trash-*/",
            "- .DS_Store",
            "- .AppleDouble",
            "- .LSOverride",
            "- ._*",
            "- Thumbs.db",
            "- ehthumbs.db",
            "- desktop.ini",
            "- $RECYCLE.BIN/",
            "- ~$*",
            "- *.tmp",
            "- *.temp",
            "- *.part",
            "- *.crdownload",
            "- *.log",
            "- .cache/",
        ],
    },
    Preset {
        name: "dev_dirs",
        rules: &[
            "- .git/",
            "- node_modules/",
            "- target/",
            "- .venv/",
            "- __pycache__/",
        ],
    },
    Preset {
        name: GIT_REPOS,
        rules: &[],
    },
];

#[must_use]
pub fn preset(name: &str) -> Option<&'static Preset> {
    PRESETS.iter().find(|preset| preset.name == name)
}

/// The filters-file for `pair`: custom lines first, then the enabled presets,
/// then (with `git_repos`) one anchored rule per entry of `git_repos`.
/// Preset names the pair lists but that do not exist are skipped; config
/// validation reports them.
#[must_use]
pub fn render(pair: &Pair, git_repos: &[String]) -> String {
    let enabled = |name: &str| pair.presets.iter().any(|preset| preset == name);
    let mut out = String::from(GENERATED_HEADER);
    out.push('\n');
    for line in &pair.filters {
        out.push_str(line);
        out.push('\n');
    }
    for preset in &PRESETS {
        if enabled(preset.name) {
            for rule in preset.rules {
                out.push_str(rule);
                out.push('\n');
            }
        }
    }
    if enabled(GIT_REPOS) {
        for repo in git_repos {
            out.push_str("- /");
            for ch in repo.chars() {
                if matches!(ch, '\\' | '*' | '?' | '[' | ']' | '{' | '}') {
                    out.push('\\');
                }
                out.push(ch);
            }
            out.push_str("/\n");
        }
    }
    out
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rendered {
    pub text: String,
    pub git_repos: Vec<String>,
}

/// [`render`] with the repositories found now under `pair.local`. Without the
/// `git_repos` preset it does no I/O. A failed scan renders no repo rules,
/// which changes the hash and so holds the sync for review.
pub async fn render_live(pair: &Pair) -> Rendered {
    if !pair.presets.iter().any(|name| name == GIT_REPOS) {
        return Rendered {
            text: render(pair, &[]),
            git_repos: Vec::new(),
        };
    }
    let root = pair.local.clone();
    let skip = DirMatcher::new(&render(pair, &[]));
    let git_repos = tokio::task::spawn_blocking(move || find_git_repos(&root, &skip))
        .await
        .unwrap_or_else(|err| {
            log::warn!("git repository scan failed: {err}");
            Vec::new()
        });
    Rendered {
        text: render(pair, &git_repos),
        git_repos,
    }
}

/// Folders under `root` that hold a `.git` (directory or file, so worktrees
/// and submodules count), as `/`-joined paths relative to `root`, sorted.
/// The root itself is never listed, repos are not descended into and
/// directories `skip` leaves out are not scanned. Symlinks are not followed.
#[must_use]
pub fn find_git_repos(root: &Path, skip: &DirMatcher) -> Vec<String> {
    let mut repos = Vec::new();
    let mut stack = vec![(PathBuf::new(), String::new())];
    while let Some((rel, name)) = stack.pop() {
        let dir = root.join(&rel);
        let is_root = name.is_empty();
        if !is_root && dir.join(".git").symlink_metadata().is_ok() {
            repos.push(name);
            continue;
        }
        let entries = match std::fs::read_dir(&dir) {
            Ok(entries) => entries,
            Err(err) if is_root && err.kind() == std::io::ErrorKind::NotFound => break,
            Err(err) => {
                log::warn!("cannot scan {} for git repositories: {err}", dir.display());
                continue;
            }
        };
        for entry in entries.filter_map(Result::ok) {
            if !entry.file_type().is_ok_and(|kind| kind.is_dir()) || entry.file_name() == ".git" {
                continue;
            }
            let file_name = entry.file_name();
            let Some(part) = file_name.to_str().filter(|part| !part.contains('\n')) else {
                log::warn!("skipping {}: not a usable path", entry.path().display());
                continue;
            };
            let child = rel.join(part);
            if !skip.is_excluded(&child) {
                let child_name = if is_root {
                    part.to_owned()
                } else {
                    format!("{name}/{part}")
                };
                stack.push((child, child_name));
            }
        }
    }
    repos.sort();
    repos
}

/// SHA-256 of `rendered`, lowercase hex.
#[must_use]
pub fn hash(rendered: &str) -> String {
    let digest = Sha256::digest(rendered.as_bytes());
    let mut hex = String::with_capacity(digest.len() * 2);
    for byte in digest {
        let _ = write!(hex, "{byte:02x}");
    }
    hex
}

#[derive(Debug, thiserror::Error)]
pub enum FiltersError {
    #[error("cannot read {}: {source}", path.display())]
    Read {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("cannot write {}: {source}", path.display())]
    Write {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FiltersFile {
    pub path: PathBuf,
    pub hash: String,
    pub rendered: String,
    pub git_repos: Vec<String>,
}

/// Renders `pair` into `<state>/syncfast/filters/<id>.txt`, touching the file
/// only when its content changes so rclone's `.md5` beside it stays valid.
///
/// # Errors
/// The existing file cannot be read or the new one cannot be written.
pub async fn write_if_changed(paths: &Paths, pair: &Pair) -> Result<FiltersFile, FiltersError> {
    let path = paths.filters_file(&pair.id);
    let Rendered {
        text: rendered,
        git_repos,
    } = render_live(pair).await;
    let hash = hash(&rendered);
    let current = match tokio::fs::read(&path).await {
        Ok(bytes) => Some(bytes),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => None,
        Err(source) => {
            return Err(FiltersError::Read { path, source });
        }
    };
    if current.as_deref() == Some(rendered.as_bytes()) {
        return Ok(FiltersFile {
            path,
            hash,
            rendered,
            git_repos,
        });
    }
    let target = path.clone();
    let content = rendered.clone();
    let outcome = tokio::task::spawn_blocking(move || fastframe_file::write(&target, content))
        .await
        .unwrap_or_else(|join| Err(std::io::Error::other(join)));
    match outcome {
        Ok(()) => Ok(FiltersFile {
            path,
            hash,
            rendered,
            git_repos,
        }),
        Err(source) => Err(FiltersError::Write { path, source }),
    }
}

/// Answers "is this directory excluded?" from the directory rules (`- x/`) of
/// a rendered filters-file. File rules are ignored; a single `+ ` rule turns
/// the matcher off, because include rules can re-admit anything.
#[derive(Debug, Clone)]
pub struct DirMatcher {
    set: GlobSet,
    disabled: bool,
}

impl DirMatcher {
    #[must_use]
    pub fn new(rendered: &str) -> Self {
        let mut builder = GlobSetBuilder::new();
        let mut disabled = false;
        for line in rendered.lines() {
            if line.starts_with("+ ") {
                disabled = true;
                continue;
            }
            let Some(pattern) = line.strip_prefix("- ").and_then(|p| p.strip_suffix('/')) else {
                continue;
            };
            let glob = match pattern.strip_prefix('/') {
                Some(anchored) => anchored.to_owned(),
                None => format!("**/{pattern}"),
            };
            match GlobBuilder::new(&glob).literal_separator(true).build() {
                Ok(glob) => {
                    builder.add(glob);
                }
                Err(err) => log::warn!("ignoring directory filter {line:?}: {err}"),
            }
        }
        let set = builder.build().unwrap_or_else(|err| {
            log::warn!("directory filters are unusable: {err}");
            GlobSet::empty()
        });
        Self { set, disabled }
    }

    /// `rel_dir` is relative to the pair's root. A directory is excluded when
    /// it, or any directory above it, matches a rule.
    #[must_use]
    pub fn is_excluded(&self, rel_dir: &Path) -> bool {
        if self.disabled {
            return false;
        }
        rel_dir
            .ancestors()
            .filter(|dir| !dir.as_os_str().is_empty())
            .any(|dir| self.set.is_match(dir))
    }
}

/// How many top-level folders [`summarize_exclusions`] lists.
pub const TOP_FOLDERS: usize = 20;

/// What a filter test found: how many of the files the rules leave out and
/// where.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExclusionSummary {
    pub total: usize,
    pub excluded: usize,
    /// Top-level folders with the most excluded files, most first and then
    /// by name, at most [`TOP_FOLDERS`]. Files at the top level are only in
    /// `excluded`.
    pub folders: Vec<(String, usize)>,
    /// Folders left out because they hold a `.git`.
    pub git_repos: Vec<String>,
}

/// Compares the files of a folder (`all`) with the ones the filters keep
/// (`kept`), both as `rclone lsf -R` lists them.
#[must_use]
pub fn summarize_exclusions(
    all: &[String],
    kept: &[String],
    git_repos: Vec<String>,
) -> ExclusionSummary {
    let kept: std::collections::HashSet<&str> = kept.iter().map(String::as_str).collect();
    let mut excluded = 0;
    let mut per_folder: std::collections::BTreeMap<&str, usize> = std::collections::BTreeMap::new();
    for file in all.iter().filter(|file| !kept.contains(file.as_str())) {
        excluded += 1;
        if let Some((folder, _)) = file.split_once('/') {
            *per_folder.entry(folder).or_default() += 1;
        }
    }
    let mut folders: Vec<(String, usize)> = per_folder
        .into_iter()
        .map(|(folder, count)| (folder.to_owned(), count))
        .collect();
    folders.sort_by_key(|(_, count)| std::cmp::Reverse(*count));
    folders.truncate(TOP_FOLDERS);
    ExclusionSummary {
        total: all.len(),
        excluded,
        folders,
        git_repos,
    }
}

