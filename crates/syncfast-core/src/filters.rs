//! Filter presets, the rendered rclone filters-file and the directory
//! matcher used by the watcher and the conflict scan.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use globset::{GlobBuilder, GlobSet, GlobSetBuilder};
use sha2::{Digest as _, Sha256};

use crate::config::Pair;
use crate::paths::Paths;

pub const GENERATED_HEADER: &str = "# Generated by syncfast. Do not edit.";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Preset {
    pub name: &'static str,
    pub rules: &'static [&'static str],
}

/// In render order.
pub const PRESETS: [Preset; 2] = [
    Preset {
        name: "system_junk",
        rules: &[
            "- .directory",
            "- .Trash-*/",
            "- .DS_Store",
            "- .AppleDouble",
            "- .LSOverride",
            "- ._*",
            "- Thumbs.db",
            "- ehthumbs.db",
            "- desktop.ini",
            "- $RECYCLE.BIN/",
            "- ~$*",
            "- *.tmp",
            "- *.temp",
            "- *.part",
            "- *.crdownload",
            "- *.log",
            "- .cache/",
        ],
    },
    Preset {
        name: "dev_dirs",
        rules: &[
            "- .git/",
            "- node_modules/",
            "- target/",
            "- .venv/",
            "- __pycache__/",
        ],
    },
];

#[must_use]
pub fn preset(name: &str) -> Option<&'static Preset> {
    PRESETS.iter().find(|preset| preset.name == name)
}

/// The filters-file for `pair`: custom lines first, then the enabled presets.
/// Preset names the pair lists but that do not exist are skipped; config
/// validation reports them.
#[must_use]
pub fn render(pair: &Pair) -> String {
    let mut out = String::from(GENERATED_HEADER);
    out.push('\n');
    for line in &pair.filters {
        out.push_str(line);
        out.push('\n');
    }
    for preset in &PRESETS {
        if pair.presets.iter().any(|name| name == preset.name) {
            for rule in preset.rules {
                out.push_str(rule);
                out.push('\n');
            }
        }
    }
    out
}

/// SHA-256 of `rendered`, lowercase hex.
#[must_use]
pub fn hash(rendered: &str) -> String {
    let digest = Sha256::digest(rendered.as_bytes());
    let mut hex = String::with_capacity(digest.len() * 2);
    for byte in digest {
        let _ = write!(hex, "{byte:02x}");
    }
    hex
}

#[derive(Debug, thiserror::Error)]
pub enum FiltersError {
    #[error("cannot read {}: {source}", path.display())]
    Read {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
    #[error("cannot write {}: {source}", path.display())]
    Write {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FiltersFile {
    pub path: PathBuf,
    pub hash: String,
}

/// Renders `pair` into `<state>/syncfast/filters/<id>.txt`, touching the file
/// only when its content changes so rclone's `.md5` beside it stays valid.
///
/// # Errors
/// The existing file cannot be read or the new one cannot be written.
pub async fn write_if_changed(paths: &Paths, pair: &Pair) -> Result<FiltersFile, FiltersError> {
    let path = paths.filters_file(&pair.id);
    let rendered = render(pair);
    let hash = hash(&rendered);
    let current = match tokio::fs::read(&path).await {
        Ok(bytes) => Some(bytes),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => None,
        Err(source) => {
            return Err(FiltersError::Read { path, source });
        }
    };
    if current.as_deref() == Some(rendered.as_bytes()) {
        return Ok(FiltersFile { path, hash });
    }
    let target = path.clone();
    let outcome = tokio::task::spawn_blocking(move || fastframe_file::write(&target, rendered))
        .await
        .unwrap_or_else(|join| Err(std::io::Error::other(join)));
    match outcome {
        Ok(()) => Ok(FiltersFile { path, hash }),
        Err(source) => Err(FiltersError::Write { path, source }),
    }
}

/// Answers "is this directory excluded?" from the directory rules (`- x/`) of
/// a rendered filters-file. File rules are ignored; a single `+ ` rule turns
/// the matcher off, because include rules can re-admit anything.
#[derive(Debug, Clone)]
pub struct DirMatcher {
    set: GlobSet,
    disabled: bool,
}

impl DirMatcher {
    #[must_use]
    pub fn new(rendered: &str) -> Self {
        let mut builder = GlobSetBuilder::new();
        let mut disabled = false;
        for line in rendered.lines() {
            if line.starts_with("+ ") {
                disabled = true;
                continue;
            }
            let Some(pattern) = line.strip_prefix("- ").and_then(|p| p.strip_suffix('/')) else {
                continue;
            };
            let glob = match pattern.strip_prefix('/') {
                Some(anchored) => anchored.to_owned(),
                None => format!("**/{pattern}"),
            };
            match GlobBuilder::new(&glob).literal_separator(true).build() {
                Ok(glob) => {
                    builder.add(glob);
                }
                Err(err) => log::warn!("ignoring directory filter {line:?}: {err}"),
            }
        }
        let set = builder.build().unwrap_or_else(|err| {
            log::warn!("directory filters are unusable: {err}");
            GlobSet::empty()
        });
        Self { set, disabled }
    }

    /// `rel_dir` is relative to the pair's root. A directory is excluded when
    /// it, or any directory above it, matches a rule.
    #[must_use]
    pub fn is_excluded(&self, rel_dir: &Path) -> bool {
        if self.disabled {
            return false;
        }
        rel_dir
            .ancestors()
            .filter(|dir| !dir.as_os_str().is_empty())
            .any(|dir| self.set.is_match(dir))
    }
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;

    use super::*;

    fn pair(presets: &[&str], filters: &[&str]) -> Pair {
        Pair {
            id: "drive".into(),
            name: "Drive".into(),
            local: PathBuf::from("/home/ada/Drive"),
            remote: "gdrive:".into(),
            enabled: true,
            presets: presets.iter().map(|s| (*s).to_owned()).collect(),
            filters: filters.iter().map(|s| (*s).to_owned()).collect(),
        }
    }

    fn matcher(rules: &[&str]) -> DirMatcher {
        DirMatcher::new(&rules.join("\n"))
    }

    fn excluded(matcher: &DirMatcher, dir: &str) -> bool {
        matcher.is_excluded(Path::new(dir))
    }

    #[test]
    fn render_is_the_header_then_custom_lines_then_both_presets_in_fixed_order() {
        let rendered = render(&pair(
            &["dev_dirs", "system_junk"],
            &["+ keep/**", "- *.bak"],
        ));

        assert_eq!(
            rendered,
            "\
# Generated by syncfast. Do not edit.
+ keep/**
- *.bak
- .directory
- .Trash-*/
- .DS_Store
- .AppleDouble
- .LSOverride
- ._*
- Thumbs.db
- ehthumbs.db
- desktop.ini
- $RECYCLE.BIN/
- ~$*
- *.tmp
- *.temp
- *.part
- *.crdownload
- *.log
- .cache/
- .git/
- node_modules/
- target/
- .venv/
- __pycache__/
"
        );
    }

    #[test]
    fn render_without_presets_or_filters_is_only_the_header() {
        assert_eq!(render(&pair(&[], &[])), format!("{GENERATED_HEADER}\n"));
    }

    #[test]
    fn render_with_only_dev_dirs_omits_system_junk() {
        let rendered = render(&pair(&["dev_dirs"], &[]));

        assert!(rendered.contains("- node_modules/\n"));
        assert!(!rendered.contains("Thumbs.db"));
    }

    #[test]
    fn hash_is_sha256_hex() {
        assert_eq!(
            hash("abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
    }

    #[test]
    fn hash_differs_when_a_filter_changes() {
        let before = hash(&render(&pair(&["dev_dirs"], &[])));
        let after = hash(&render(&pair(&["dev_dirs"], &["- *.bak"])));

        assert_ne!(before, after);
    }

    fn paths_in(root: &Path) -> Paths {
        Paths::new(
            root.into(),
            root.join("c"),
            root.join("s"),
            root.join("d"),
            root.join("r"),
        )
    }

    fn backdate(path: &Path) -> std::time::SystemTime {
        let past = std::time::UNIX_EPOCH + std::time::Duration::from_secs(1_000_000);
        std::fs::File::options()
            .write(true)
            .open(path)
            .unwrap()
            .set_modified(past)
            .unwrap();
        past
    }

    fn mtime(path: &Path) -> std::time::SystemTime {
        std::fs::metadata(path).unwrap().modified().unwrap()
    }

    #[tokio::test]
    async fn write_if_changed_creates_the_file_with_the_rendered_content() {
        let tmp = tempfile::tempdir().unwrap();
        let paths = paths_in(tmp.path());
        let pair = pair(&["dev_dirs"], &[]);

        let file = write_if_changed(&paths, &pair).await.unwrap();

        assert_eq!(file.path, paths.state_dir().join("filters/drive.txt"));
        assert_eq!(file.hash, hash(&render(&pair)));
        assert_eq!(std::fs::read_to_string(&file.path).unwrap(), render(&pair));
    }

    #[tokio::test]
    async fn write_if_changed_leaves_the_file_untouched_when_the_content_is_identical() {
        let tmp = tempfile::tempdir().unwrap();
        let paths = paths_in(tmp.path());
        let pair = pair(&["dev_dirs"], &[]);
        let first = write_if_changed(&paths, &pair).await.unwrap();
        let past = backdate(&first.path);

        let second = write_if_changed(&paths, &pair).await.unwrap();

        assert_eq!(second, first);
        assert_eq!(mtime(&second.path), past);
    }

    #[tokio::test]
    async fn write_if_changed_rewrites_when_the_filters_change() {
        let tmp = tempfile::tempdir().unwrap();
        let paths = paths_in(tmp.path());
        let first = write_if_changed(&paths, &pair(&[], &[])).await.unwrap();
        let past = backdate(&first.path);

        let changed = write_if_changed(&paths, &pair(&[], &["- *.bak"]))
            .await
            .unwrap();

        assert_ne!(changed.hash, first.hash);
        assert!(
            std::fs::read_to_string(&changed.path)
                .unwrap()
                .contains("- *.bak")
        );
        assert_ne!(mtime(&changed.path), past);
    }

    #[tokio::test]
    async fn a_filters_path_that_cannot_be_read_is_a_read_error_and_is_left_alone() {
        let tmp = tempfile::tempdir().unwrap();
        let paths = paths_in(tmp.path());
        std::fs::create_dir_all(paths.filters_file("drive")).unwrap();

        let result = write_if_changed(&paths, &pair(&[], &[])).await;

        assert!(
            matches!(result, Err(FiltersError::Read { .. })),
            "{result:?}"
        );
        assert!(paths.filters_file("drive").is_dir());
    }

    #[test]
    fn unanchored_rule_matches_at_any_depth() {
        let m = matcher(&["- node_modules/"]);

        assert!(excluded(&m, "node_modules"));
        assert!(excluded(&m, "web/app/node_modules"));
        assert!(!excluded(&m, "web/app"));
        assert!(!excluded(&m, "my_node_modules"));
    }

    #[test]
    fn anchored_rule_matches_only_at_the_root() {
        let m = matcher(&["- /build/"]);

        assert!(excluded(&m, "build"));
        assert!(!excluded(&m, "src/build"));
    }

    #[test]
    fn directories_below_an_excluded_one_are_excluded() {
        let m = matcher(&["- /build/"]);

        assert!(excluded(&m, "build/out/deep"));
    }

    #[test]
    fn star_and_question_mark_do_not_cross_a_slash() {
        let m = matcher(&["- /foo*/bar/", "- /a?c/"]);

        assert!(excluded(&m, "foox/bar"));
        assert!(excluded(&m, "foo/bar"));
        assert!(!excluded(&m, "foo/x/bar"));
        assert!(excluded(&m, "abc"));
        assert!(!excluded(&m, "a/c"));
    }

    #[test]
    fn double_star_crosses_slashes() {
        let m = matcher(&["- /docs/**/tmp/"]);

        assert!(excluded(&m, "docs/tmp"));
        assert!(excluded(&m, "docs/a/b/tmp"));
        assert!(!excluded(&m, "other/docs/tmp"));
    }

    #[test]
    fn preset_directory_globs_apply() {
        let m = DirMatcher::new(&render(&pair(&["system_junk", "dev_dirs"], &[])));

        assert!(excluded(&m, "photos/.Trash-1000"));
        assert!(excluded(&m, "proj/.git"));
        assert!(excluded(&m, ".cache"));
        assert!(!excluded(&m, "photos"));
    }

    #[test]
    fn file_rules_and_comments_do_not_exclude_directories() {
        let m = matcher(&["# note/", "- *.log", "- Thumbs.db"]);

        assert!(!excluded(&m, "note"));
        assert!(!excluded(&m, "debug.log"));
        assert!(!excluded(&m, "Thumbs.db"));
    }

    #[test]
    fn any_include_rule_turns_the_matcher_off() {
        let m = matcher(&["- node_modules/", "+ keep/**"]);

        assert!(!excluded(&m, "node_modules"));
    }

    #[test]
    fn empty_path_is_never_excluded() {
        let m = matcher(&["- **/"]);

        assert!(!excluded(&m, ""));
    }
}
