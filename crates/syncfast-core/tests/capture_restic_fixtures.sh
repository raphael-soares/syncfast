#!/usr/bin/env bash
# Captures real restic output and exit codes for the parser tests.
# Usage: just capture-restic-fixtures [scenario...] (needs restic and rclone on
# PATH; touches only a tempdir). Scenario names are the group names used below;
# with names, only those fixtures are rewritten. The backup_status group
# writes 1.5 GiB of random data, so the tempdir goes to /dev/shm when it exists.
set -euo pipefail

if [[ "$(id -u)" -eq 0 ]]; then
  echo "refusing to run as root: chmod 000 does not block root" >&2
  exit 1
fi

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
version="$(restic version | head -n 1 | sed -E 's/^restic ([0-9.]+).*/\1/')"
out="$here/fixtures/restic-$version"
mkdir -p "$out"
only=("$@")

wanted() {
  [[ ${#only[@]} -eq 0 ]] && return 0
  local name
  for name in "${only[@]}"; do
    [[ "$name" == "$1" ]] && return 0
  done
  return 1
}

base=/dev/shm
[[ -d "$base" && -w "$base" ]] || base="${TMPDIR:-/tmp}"
root="$(mktemp -d "$base/syncfast-restic.XXXXXX")"
trap 'chmod -R u+rwX "$root" 2>/dev/null || true; rm -rf "$root"' EXIT
export RCLONE_CONFIG="$root/rclone.conf"
printf '[testremote]\ntype = local\n' > "$RCLONE_CONFIG"
export RESTIC_CACHE_DIR="$root/cache"
export RESTIC_PROGRESS_FPS=1
unset RESTIC_PASSWORD RESTIC_PASSWORD_FILE RESTIC_PASSWORD_COMMAND RESTIC_REPOSITORY RESTIC_REPOSITORY_FILE

key=ABCDEFGHIJKLMNOPQRSTUVWXYZ234567ABCDEFGHIJKLMNOPQRST
wrong=ZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZ
host=fixture-host
repo="$root/repo"
src="$root/src"
rclone_bin="$(command -v rclone)"

# restic against $repo with the key on stdin, as the wrapper does.
R() {
  printf '%s' "${use_key:-$key}" | restic \
    -r "rclone:testremote:${use_repo:-$repo}" \
    -o "rclone.program=$rclone_bin" \
    -o "rclone.args=serve restic --stdio --b2-hard-delete --drive-use-trash=false" \
    --password-file /dev/stdin "$@"
}

# Hides the machine from the committed files.
sanitize() {
  local file="$1" user machine
  user="$(id -un)"
  machine="$(hostname)"
  sed -i -e "s|$root|/tmp/fixture|g" -e "s|\\b$user\\b|user|g" -e "s|\\b$machine\\b|$host|g" "$file"
}

capture() { # capture <name> <command...>
  local name="$1"
  shift
  wanted "$GROUP" || return 0
  local code=0
  "$@" > "$out/$name.out" 2> "$out/$name.err" || code=$?
  echo "$code" > "$out/$name.exit"
  sanitize "$out/$name.out"
  sanitize "$out/$name.err"
  echo "$name: exit $code"
}

fresh_repo() {
  rm -rf "$repo" "$root/cache"
  R init --quiet > /dev/null 2>&1
}

put() { # put <file> <content>
  mkdir -p "$(dirname "$1")"
  printf '%s\n' "$2" > "$1"
}

small_tree() {
  rm -rf "$src"
  put "$src/docs/a.txt" "alpha"
  put "$src/docs/notes.log" "a log"
  put "$src/docs/sub/b.txt" "beta"
  put "$src/pics/p1.txt" "picture one"
  put "$src/pics/p2.txt" "picture two"
}

B() { R backup --json --host "$host" "$@"; }

GROUP=init
rm -rf "$repo"
capture init R init --json

GROUP=backup_ok
fresh_repo
small_tree
capture backup_ok B "$src/docs" "$src/pics"

GROUP=backup_status
if wanted "$GROUP"; then
  fresh_repo
  rm -rf "$src"
  mkdir -p "$src"
  head -c 1610612736 /dev/urandom > "$src/big.bin"
  put "$src/small.txt" "small"
fi
capture backup_status B "$src"
rm -rf "$root/restore"
capture restore_status R restore latest --target "$root/restore" --json
rm -rf "$src" "$root/restore"

GROUP=backup_unreadable
fresh_repo
small_tree
chmod 000 "$src/docs/sub/b.txt"
capture backup_unreadable B "$src/docs"
chmod 644 "$src/docs/sub/b.txt"

GROUP=backup_missing_path
fresh_repo
small_tree
capture backup_missing_path B "$src/docs" "$src/does-not-exist"

GROUP=backup_excludes
fresh_repo
rm -rf "$src"
put "$src/keep.txt" "keep"
put "$src/~\$doc.docx" "lock file"
put "$src/\$RECYCLE.BIN/x.txt" "bin"
put "$src/data.log" "log"
printf '# Generated by syncfast. Do not edit.\n~$$*\n$$RECYCLE.BIN\n*.log\n' > "$root/excludes-escaped.txt"
printf '# Generated by syncfast. Do not edit.\n~$*\n$RECYCLE.BIN\n*.log\n' > "$root/excludes-raw.txt"
capture backup_excludes_escaped B --exclude-file "$root/excludes-escaped.txt" "$src"
capture backup_excludes_escaped_ls R ls latest --json --recursive
capture backup_excludes_raw B --exclude-file "$root/excludes-raw.txt" "$src"
capture backup_excludes_raw_ls R ls latest --json --recursive

GROUP=backup_dry_run
fresh_repo
rm -rf "$src"
put "$src/keep.txt" "keep"
put "$src/data.log" "log"
put "$src/more.log" "more log"
printf '*.log\n' > "$root/excludes.txt"
capture backup_dry_run_plain B --dry-run -vv "$src"
capture backup_dry_run_excluded B --dry-run -vv --exclude-file "$root/excludes.txt" "$src"

GROUP=snapshots
fresh_repo
small_tree
B --time "2026-01-01 10:00:00" "$src/docs" > /dev/null 2>&1 || true
put "$src/docs/c.txt" "gamma"
B --time "2026-01-02 10:00:00" "$src/docs" > /dev/null 2>&1 || true
B --time "2026-01-03 10:00:00" "$src/docs" "$src/pics" > /dev/null 2>&1 || true
capture snapshots R snapshots --json

GROUP=ls
fresh_repo
small_tree
B "$src/docs" > /dev/null 2>&1 || true
capture ls_dir R ls latest "$src/docs" --json
capture ls_recursive R ls latest "$src/docs" --json --recursive

GROUP=forget_prune
fresh_repo
small_tree
B --time "2026-01-01 10:00:00" "$src/docs" "$src/pics" > /dev/null 2>&1 || true
B --time "2026-01-02 10:00:00" "$src/docs" > /dev/null 2>&1 || true
B --time "2026-01-03 10:00:00" "$src/docs" > /dev/null 2>&1 || true
capture forget_prune R forget --host "$host" --group-by host --keep-daily 1 --prune --json
capture forget_prune_snapshots R snapshots --json

GROUP=forget_two_hosts
fresh_repo
small_tree
for h in a b; do
  R backup --json --host "$h" --time "2026-01-01 10:00:00" "$src/docs" > /dev/null 2>&1 || true
  R backup --json --host "$h" --time "2026-01-02 10:00:00" "$src/docs" > /dev/null 2>&1 || true
done
capture forget_two_hosts R forget --host a --group-by host --keep-daily 1 --json
capture forget_two_hosts_snapshots R snapshots --json

GROUP=check
fresh_repo
small_tree
B "$src/docs" > /dev/null 2>&1 || true
capture check_ok R check --json
capture check_sample R check --read-data-subset=5% --json

GROUP=check_damaged
fresh_repo
small_tree
B "$src/docs" "$src/pics" > /dev/null 2>&1 || true
pack="$(find "$repo/data" -type f | head -n 1)"
dd if=/dev/zero of="$pack" bs=1 count=64 seek=40 conv=notrunc 2> /dev/null
capture check_damaged R check --read-data --json

GROUP=restore
fresh_repo
small_tree
B "$src/docs" "$src/pics" > /dev/null 2>&1 || true
rm -rf "$root/r1" "$root/r2" "$root/r3" "$root/r4"
capture restore_include R restore latest --target "$root/r1" --include "$src/docs/a.txt" --json
capture restore_subfolder R restore "latest:$src/docs" --target "$root/r2" --include /sub --json
capture restore_no_match R restore latest --target "$root/r3" --include "$src/nothing-here" --json
capture restore_dry_run R restore latest --target "$root/r4" --dry-run --json

GROUP=wrong_password
fresh_repo
use_key="$wrong" capture wrong_password R snapshots --json

GROUP=no_repo
use_repo="$root/nope" capture no_repo R snapshots --json

GROUP=locked
if wanted "$GROUP"; then
  fresh_repo
  rm -rf "$src"
  mkdir -p "$src"
  head -c 400000000 /dev/urandom > "$src/chunk.bin"
  restic -r "rclone:testremote:$repo" \
    -o "rclone.program=$rclone_bin" \
    -o "rclone.args=serve restic --stdio --b2-hard-delete --drive-use-trash=false" \
    --password-file /dev/stdin backup --json --host "$host" --limit-upload 20000 "$src" \
    < <(printf '%s' "$key") > /dev/null 2>&1 &
  pid=$!
  for _ in $(seq 1 100); do
    if [[ -n "$(find "$repo/locks" -type f 2> /dev/null | head -n 1)" ]]; then break; fi
    sleep 0.2
  done
  kill -9 "$pid" 2> /dev/null || true
  wait "$pid" 2> /dev/null || true
  sleep 1
fi
capture locked R forget --host "$host" --group-by host --keep-daily 1 --json
capture unlock R unlock
