#!/usr/bin/env bash
# Captures real `rclone bisync` JSON logs and exit codes for the parser tests.
# Usage: just capture-fixtures [scenario...] (needs rclone on PATH; touches only
# a tempdir). With scenario names, only those fixtures are rewritten.
set -euo pipefail

if [[ "$(id -u)" -eq 0 ]]; then
  echo "refusing to run as root: chmod 555 does not block root" >&2
  exit 1
fi

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
version="$(rclone version | head -n 1 | sed -E 's/^rclone v?//')"
out="$here/fixtures/rclone-$version"
mkdir -p "$out"
only=("$@")

wanted() {
  [[ ${#only[@]} -eq 0 ]] && return 0
  local name
  for name in "${only[@]}"; do
    [[ "$name" == "$1" ]] && return 0
  done
  return 1
}

root="$(mktemp -d)"
trap 'rm -rf "$root"' EXIT
export RCLONE_CONFIG="$root/rclone.conf"
: > "$RCLONE_CONFIG"

stamp="20260101-120000"
old="2026-01-01T10:00:00"
mid="2026-01-01T11:00:00"
new="2026-01-01T12:00:00"

# Per scenario: fresh local/ remote/ state/ data/ and a filters file.
setup() {
  rm -rf "$root/local" "$root/remote" "$root/state" "$root/data"
  mkdir -p "$root/local" "$root/remote" "$root/state/filters" "$root/state/bisync/x" "$root/data/versions/x"
  printf '# Generated by syncfast. Do not edit.\n- *.tmp\n' > "$root/state/filters/x.txt"
}

# Same flags as bisync_args in the spec; extra flags go last so they win.
bisync() {
  local log="$1"
  shift
  rclone bisync "$root/local" "$root/remote" \
    --filters-file "$root/state/filters/x.txt" \
    --workdir "$root/state/bisync/x/" \
    --resilient --recover --max-lock 2m \
    --conflict-resolve newer --conflict-loser num \
    --max-delete 50 \
    --create-empty-src-dirs \
    --drive-skip-gdocs \
    --backup-dir1 "$root/data/versions/x/$stamp/" \
    --stats 2s --stats-log-level NOTICE \
    --use-json-log --log-file "$log" -v \
    "$@"
}

prepare() {
  bisync "$root/setup.jsonl" --resync --resync-mode newer
}

capture() {
  local name="$1"
  shift
  wanted "$name" || return 0
  local code=0
  rm -f "$out/$name.jsonl"
  bisync "$out/$name.jsonl" "$@" || code=$?
  echo "$code" > "$out/$name.exit"
  echo "$name: exit $code"
}

put() { # put <file> <content> <mtime>
  mkdir -p "$(dirname "$1")"
  printf '%s\n' "$2" > "$1"
  touch -d "$3" "$1"
}

seed_four() {
  for n in 1 2 3 4; do
    put "$root/local/f$n.txt" "file $n" "$old"
  done
}

# 1 and 2: first run. Two files only local, one only remote, one differing
# on both sides with the remote newer.
first_run_files() {
  setup
  put "$root/local/a.txt" "local only a" "$old"
  put "$root/local/b.txt" "local only b" "$old"
  put "$root/remote/c.txt" "remote only c" "$old"
  put "$root/local/d.txt" "local d" "$old"
  put "$root/remote/d.txt" "remote d is newer" "$new"
}
first_run_files
capture resync_dry_run --resync --resync-mode newer --dry-run
first_run_files
capture resync --resync --resync-mode newer

setup
put "$root/local/base.txt" "base" "$old"
prepare
put "$root/local/up.txt" "new local file" "$mid"
capture upload

setup
put "$root/local/base.txt" "base" "$old"
prepare
capture no_changes

setup
put "$root/local/base.txt" "base" "$old"
prepare
mkdir -p "$root/local/empty/inner"
put "$root/local/dir/nested.txt" "nested" "$mid"
capture new_dirs

setup
put "$root/local/base.txt" "base" "$old"
prepare
mkdir -p "$root/local/empty/inner"
put "$root/local/dir/nested.txt" "nested" "$mid"
capture new_dirs_dry_run --force --dry-run

setup
put "$root/local/base.txt" "base" "$old"
prepare
put "$root/remote/down.txt" "new remote file" "$mid"
capture download

setup
put "$root/local/doc.txt" "base" "$old"
put "$root/local/keep.txt" "unchanged" "$old"
prepare
put "$root/local/doc.txt" "local edit" "$mid"
put "$root/remote/doc.txt" "remote edit, newer" "$new"
capture conflict

# Both sides edited after the first run; only the conflict flags differ.
both_edited() {
  setup
  put "$root/local/doc.txt" "base" "$old"
  put "$root/local/keep.txt" "unchanged" "$old"
  prepare
  put "$root/local/doc.txt" "local edit" "$mid"
  put "$root/remote/doc.txt" "remote edit, newer" "$new"
}
both_edited
capture conflict_none --conflict-resolve none
both_edited
capture conflict_pathname --conflict-resolve newer --conflict-loser pathname --conflict-suffix path
both_edited
capture conflict_pathname_none --conflict-resolve none --conflict-loser pathname --conflict-suffix path
both_edited
capture conflict_delete --conflict-resolve newer --conflict-loser delete
both_edited
capture conflict_local_wins --conflict-resolve path1

setup
put "$root/local/doc.txt" "base" "$old"
put "$root/local/keep.txt" "unchanged" "$old"
prepare
put "$root/remote/doc.txt" "remote edit" "$new"
capture overwrite_local

setup
put "$root/local/doc.txt" "base" "$old"
put "$root/local/keep.txt" "unchanged" "$old"
prepare
put "$root/local/doc.txt" "local edit" "$new"
capture overwrite_remote

setup
seed_four
prepare
rm "$root/local/f1.txt" "$root/local/f2.txt" "$root/local/f3.txt"
capture too_many_deletes

setup
seed_four
prepare
rm "$root/local/f1.txt"
capture delete_remote

setup
seed_four
prepare
rm "$root/remote/f1.txt"
capture delete_local

# Every change kind at once: delete and replace on each side, new on each side.
mixed_changes() {
  setup
  seed_four
  prepare
  rm "$root/local/f1.txt"
  put "$root/local/f2.txt" "file 2 edited locally" "$new"
  put "$root/local/n1.txt" "new local file" "$mid"
  rm "$root/remote/f3.txt"
  put "$root/remote/f4.txt" "file 4 edited remotely" "$new"
  put "$root/remote/n2.txt" "new remote file" "$mid"
}
mixed_changes
capture mixed_dry_run --force --dry-run
mixed_changes
capture mixed

setup
seed_four
prepare
rm "$root/local/f1.txt" "$root/local/f2.txt" "$root/local/f3.txt"
capture force_dry_run --force --dry-run

setup
put "$root/local/only.txt" "base" "$old"
prepare
put "$root/local/only.txt" "edited locally, longer" "$new"
capture all_files_changed

setup
put "$root/local/base.txt" "base" "$old"
prepare
printf '# Generated by syncfast. Do not edit.\n- *.tmp\n- *.bak\n' > "$root/state/filters/x.txt"
capture filters_changed

# critical_retryable: prior listings missing; --resilient makes it retryable.
setup
put "$root/local/base.txt" "base" "$old"
prepare
for lst in "$root"/state/bisync/x/*.lst; do
  mv "$lst" "$lst-err"
done
put "$root/local/after.txt" "after" "$mid"
capture critical_retryable

# empty_prior_listing: both sides were empty at the first resync, so the
# listings bisync keeps are empty and the next normal run refuses to start.
setup
prepare
put "$root/local/after.txt" "after" "$mid"
capture empty_prior_listing

# critical: a copy fails mid-run (read-only remote), which bisync treats as
# not recoverable without --resync and leaves *.lst-err in the workdir.
setup
put "$root/local/base.txt" "base" "$old"
put "$root/local/keep.txt" "unchanged" "$old"
prepare
put "$root/local/after.txt" "after" "$mid"
chmod 555 "$root/remote"
capture critical
chmod 755 "$root/remote"
if wanted critical; then
  find "$root/state/bisync/x" -name '*.lst-err' -printf '%f\n' | sort > "$out/critical.lst-err"
fi

setup
put "$root/local/base.txt" "base" "$old"
prepare
for n in $(seq 1 200); do
  head -c 65536 /dev/urandom > "$root/local/bulk-$n.bin"
done
capture stats --stats 1s --bwlimit 2M

# One-way engine: `rclone copy` and `rclone sync` from local/ to remote/, with
# the flags oneway_args writes. The `--combined` report of each scenario is
# kept next to its log as <name>.changes.
oneway() { # oneway <copy|sync> <log> <changes> [extra flags]
  local sub="$1" log="$2" changes="$3"
  shift 3
  rclone "$sub" "$root/local" "$root/remote" \
    --filter-from "$root/state/filters/x.txt" \
    --create-empty-src-dirs \
    --drive-skip-gdocs \
    --combined "$changes" \
    --retries 1 \
    --stats 2s --stats-log-level NOTICE \
    --use-json-log --log-file "$log" -v \
    "$@"
}

capture_oneway() { # capture_oneway <name> <copy|sync> [extra flags]
  local name="oneway_$1" sub="$2"
  shift 2
  wanted "$name" || return 0
  local code=0
  rm -f "$out/$name.jsonl" "$out/$name.changes"
  oneway "$sub" "$out/$name.jsonl" "$out/$name.changes" "$@" || code=$?
  echo "$code" > "$out/$name.exit"
  echo "$name: exit $code"
}

# Every kind of line: new, identical and differing files, a folder, and a
# file only in the destination.
oneway_mixed() {
  setup
  put "$root/local/new.txt" "only in the source" "$mid"
  put "$root/local/same.txt" "identical" "$old"
  put "$root/remote/same.txt" "identical" "$old"
  put "$root/local/changed.txt" "source edit, longer" "$mid"
  put "$root/remote/changed.txt" "old" "$new"
  put "$root/local/dir/nested.txt" "nested" "$mid"
  put "$root/remote/extra.txt" "only in the destination" "$old"
}

oneway_mixed
capture_oneway copy_new copy
oneway_mixed
capture_oneway copy_changed copy --backup-dir "$root/data/versions/x/$stamp/"
oneway_mixed
capture_oneway sync_delete sync
oneway_mixed
capture_oneway sync_delete_dry_run sync --dry-run
oneway_mixed
capture_oneway sync_backup_dir sync --backup-dir "$root/data/versions/x/$stamp/"

setup
for n in 1 2 3 4; do
  put "$root/remote/f$n.txt" "file $n" "$old"
done
put "$root/local/keep.txt" "kept" "$old"
capture_oneway sync_max_delete sync --max-delete 1

setup
for n in 1 2 3; do
  put "$root/remote/f$n.txt" "file $n" "$old"
done
capture_oneway sync_empty_source sync

# An unreadable source file: rclone must not delete anything in the
# destination when a source file fails.
setup
put "$root/local/ok.txt" "readable" "$mid"
put "$root/local/locked.txt" "unreadable" "$mid"
put "$root/remote/extra.txt" "only in the destination" "$old"
chmod 000 "$root/local/locked.txt"
capture_oneway sync_errors sync
chmod 644 "$root/local/locked.txt"

# `lsf -R --files-only` as Rclone::has_files runs it: one name is enough, so
# the process is stopped after the first line.
if wanted oneway_size_json; then
  setup
  rclone lsf -R --files-only --filter-from "$root/state/filters/x.txt" "$root/local" \
    > "$out/oneway_lsf_empty.out"
  put "$root/local/a.txt" "a" "$old"
  put "$root/local/dir/b.txt" "b" "$old"
  put "$root/local/skip.tmp" "filtered out" "$old"
  rclone lsf -R --files-only --filter-from "$root/state/filters/x.txt" "$root/local" \
    | sort > "$out/oneway_lsf_files.out"
  echo "oneway_size_json: done"
fi
