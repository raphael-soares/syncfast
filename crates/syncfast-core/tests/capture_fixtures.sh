#!/usr/bin/env bash
# Captures real `rclone bisync` JSON logs and exit codes for the parser tests.
# Usage: just capture-fixtures (needs rclone on PATH; touches only a tempdir).
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
version="$(rclone version | head -n 1 | sed -E 's/^rclone v?//')"
out="$here/fixtures/rclone-$version"
mkdir -p "$out"

root="$(mktemp -d)"
trap 'rm -rf "$root"' EXIT
export RCLONE_CONFIG="$root/rclone.conf"
: > "$RCLONE_CONFIG"

stamp="20260101-120000"
old="2026-01-01T10:00:00"
mid="2026-01-01T11:00:00"
new="2026-01-01T12:00:00"

# Per scenario: fresh local/ remote/ state/ data/ and a filters file.
setup() {
  rm -rf "$root/local" "$root/remote" "$root/state" "$root/data"
  mkdir -p "$root/local" "$root/remote" "$root/state/filters" "$root/state/bisync/x" "$root/data/versions/x"
  printf '# Generated by syncfast. Do not edit.\n- *.tmp\n' > "$root/state/filters/x.txt"
}

# Same flags as bisync_args in the spec; extra flags go last so they win.
bisync() {
  local log="$1"
  shift
  rclone bisync "$root/local" "$root/remote" \
    --filters-file "$root/state/filters/x.txt" \
    --workdir "$root/state/bisync/x/" \
    --resilient --recover --max-lock 2m \
    --conflict-resolve newer --conflict-loser num \
    --max-delete 50 \
    --create-empty-src-dirs \
    --drive-skip-gdocs \
    --backup-dir1 "$root/data/versions/x/$stamp/" \
    --stats 2s --stats-log-level NOTICE \
    --use-json-log --log-file "$log" -v \
    "$@"
}

prepare() {
  bisync "$root/setup.jsonl" --resync --resync-mode newer
}

capture() {
  local name="$1"
  shift
  local code=0
  rm -f "$out/$name.jsonl"
  bisync "$out/$name.jsonl" "$@" || code=$?
  echo "$code" > "$out/$name.exit"
  echo "$name: exit $code"
}

put() { # put <file> <content> <mtime>
  mkdir -p "$(dirname "$1")"
  printf '%s\n' "$2" > "$1"
  touch -d "$3" "$1"
}

seed_four() {
  for n in 1 2 3 4; do
    put "$root/local/f$n.txt" "file $n" "$old"
  done
}

# 1 and 2: first run. Two files only local, one only remote, one differing
# on both sides with the remote newer.
first_run_files() {
  setup
  put "$root/local/a.txt" "local only a" "$old"
  put "$root/local/b.txt" "local only b" "$old"
  put "$root/remote/c.txt" "remote only c" "$old"
  put "$root/local/d.txt" "local d" "$old"
  put "$root/remote/d.txt" "remote d is newer" "$new"
}
first_run_files
capture resync_dry_run --resync --resync-mode newer --dry-run
first_run_files
capture resync --resync --resync-mode newer

setup
put "$root/local/base.txt" "base" "$old"
prepare
put "$root/local/up.txt" "new local file" "$mid"
capture upload

setup
put "$root/local/base.txt" "base" "$old"
prepare
put "$root/remote/down.txt" "new remote file" "$mid"
capture download

setup
put "$root/local/doc.txt" "base" "$old"
put "$root/local/keep.txt" "unchanged" "$old"
prepare
put "$root/local/doc.txt" "local edit" "$mid"
put "$root/remote/doc.txt" "remote edit, newer" "$new"
capture conflict

setup
put "$root/local/doc.txt" "base" "$old"
put "$root/local/keep.txt" "unchanged" "$old"
prepare
put "$root/remote/doc.txt" "remote edit" "$new"
capture overwrite_local

# overwrite_remote: the remote copy is overwritten in place (no --suffix).
setup
put "$root/local/doc.txt" "base" "$old"
put "$root/local/keep.txt" "unchanged" "$old"
prepare
put "$root/local/doc.txt" "local edit" "$new"
capture overwrite_remote

setup
seed_four
prepare
rm "$root/local/f1.txt" "$root/local/f2.txt" "$root/local/f3.txt"
capture too_many_deletes

setup
seed_four
prepare
rm "$root/local/f1.txt" "$root/local/f2.txt" "$root/local/f3.txt"
capture force_dry_run --force --dry-run

setup
put "$root/local/base.txt" "base" "$old"
prepare
printf '# Generated by syncfast. Do not edit.\n- *.tmp\n- *.bak\n' > "$root/state/filters/x.txt"
capture filters_changed

# critical_retryable: prior listings missing; --resilient makes it retryable.
setup
put "$root/local/base.txt" "base" "$old"
prepare
for lst in "$root"/state/bisync/x/*.lst; do
  mv "$lst" "$lst-err"
done
put "$root/local/after.txt" "after" "$mid"
capture critical_retryable

# critical: a copy fails mid-run (read-only remote), which bisync treats as
# not recoverable without --resync and leaves *.lst-err in the workdir.
setup
put "$root/local/base.txt" "base" "$old"
put "$root/local/keep.txt" "unchanged" "$old"
prepare
put "$root/local/after.txt" "after" "$mid"
chmod 555 "$root/remote"
capture critical
chmod 755 "$root/remote"

setup
put "$root/local/base.txt" "base" "$old"
prepare
for n in $(seq 1 200); do
  head -c 65536 /dev/urandom > "$root/local/bulk-$n.bin"
done
capture stats --stats 1s --bwlimit 2M
